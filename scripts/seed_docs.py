def make_pdf(title: str, body: str) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, title=title)
    story = [Paragraph(title, H), Spacer(1, 6)]
    for para in body.strip().split("\n"):
        story.append(Paragraph(para.strip(), P))
    doc.build(story)
    return buf.getvalue()


def main():
    for i, (block, title, body) in enumerate(DOCS, 1):
        pdf_bytes = make_pdf(title, body)
        fname = f"{i:02d}_{title[:40].replace(' ', '_').replace('/', '_')}.pdf"
        path = OUT / fname
        path.write_bytes(pdf_bytes)

        with path.open("rb") as f:
            r = requests.post(
                f"{API}/api/documents/upload",
                auth=AUTH,
                files={"file": (fname, f, "application/pdf")},
                data={"title": title, "block": block},
                timeout=120,
            )
        status = "OK" if r.ok else f"FAIL {r.status_code}: {r.text[:200]}"
        print(f"[{i:02d}] {block:8s} | {title[:50]:50s} -> {status}")

    count = requests.get(f"{API}/api/documents/count").json()
    print(f"\nИтого записей в БД (с учётом чанков): {count}")


if __name__ == "__main__":
    main()
